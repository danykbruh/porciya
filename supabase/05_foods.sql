-- =====================================================================
-- Порция — база продуктов и новые источники калорий
-- Запускать один раз: Supabase → SQL Editor → New query → вставить → Run
--
-- * foods — общий справочник продуктов (калории и БЖУ на 100 г, обычная порция).
--   Читать могут все вошедшие пользователи, менять — только разработчик (через SQL Editor).
--   Стартовый набор — усреднённые справочные значения; это ориентир, как и оценки ИИ.
-- * В meals.kcal_source добавлены источники 'base' (из базы) и 'barcode' (по штрихкоду).
-- =====================================================================
create extension if not exists pg_trgm;

create table if not exists public.foods (
  id          bigint generated always as identity primary key,
  name        text not null unique check (char_length(name) between 1 and 120),
  search      text not null,                -- название + синонимы в нижнем регистре, для поиска
  kcal100     integer not null check (kcal100 between 0 and 950),
  p100        numeric(5,1) not null check (p100 between 0 and 100),
  f100        numeric(5,1) not null check (f100 between 0 and 100),
  c100        numeric(5,1) not null check (c100 between 0 and 100),
  portion_g   integer check (portion_g between 1 and 2000),
  created_at  timestamptz not null default now()
);
create index if not exists foods_search_trgm on public.foods using gin (search gin_trgm_ops);

alter table public.foods enable row level security;
drop policy if exists "foods: read for signed-in" on public.foods;
create policy "foods: read for signed-in" on public.foods for select to authenticated using (true);
revoke all on public.foods from anon;
grant select on public.foods to authenticated;

-- Новые источники калорий в дневнике
alter table public.meals drop constraint if exists meals_kcal_source_check;
alter table public.meals add constraint meals_kcal_source_check
  check (kcal_source in ('ai','photo','recipe','fav','manual','base','barcode'));

